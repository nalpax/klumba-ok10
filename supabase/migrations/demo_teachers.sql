insert into public.teacher_flowers (teacher_id, flower_id)
select t.id, f.flower_id
from public.teachers t
join (values
  ('Иванов',    array[1,2,3]),
  ('Петрова',   array[1,5,4]),
  ('Сидорова',  array[1,4,6]),
  ('Кузнецов',  array[1,6,4]),
  ('Смирнова',  array[1,2,5]),
  ('Попов',     array[3,6,1]),
  ('Васильева', array[2,1,3]),
  ('Морозова',  array[5,4,1])
) as v(last_name, flower_ids) on v.last_name = t.last_name,
lateral unnest(v.flower_ids) as f(flower_id)
on conflict do nothing;

