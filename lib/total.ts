import { plural } from './plural';

/** «виртуальных цветов посажено …» — подпись к общему числу цветов (число пишется отдельно, крупно). */
export function totalCaption(n: number): string {
  return `${plural(n, ['виртуальный цветок посажен', 'виртуальных цветка посажено', 'виртуальных цветов посажено'])} на нашей школьной клумбе в знак благодарности учителям`;
}
