/** Стабильный «случайный» выбор по строке-ключу — один и тот же ключ всегда даёт один и тот же индекс. */
export function pickBySeed<T>(items: T[], seed: string | number): T {
  const s = String(seed);
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return items[h % items.length];
}

/** Настоящий случайный выбор — для тех случаев, когда каждый заход должен отличаться. */
export function pickRandom<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}
